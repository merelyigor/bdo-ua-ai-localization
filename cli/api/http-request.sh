#!/usr/bin/env bash
# Єдиний HTTP-шов BDO API.
#
# Таймаут запиту, HTTP 408/429/500/502/503/504 повторюються з backoff. Загальний
# бюджет повторів — 10 хвилин; після його вичерпання транспорт повертає помилку й
# поточний прогін зупиняється штатним error path виклику. Мережева відмова без
# відповіді сервера не повторюється: її код повертається одразу.
#
# ПОСТІЙНІ помилки (400, 401, 403, 404) не повторюються ніколи.
#
# Раніше тут стояв режим повтору всіх помилок, і це суперечило заголовку: відсутній
# маршрут або хибний параметр крутились ті самі 570 секунд. 2026-08-28 два
# запити до ще не розгорнутого `/glossary/terms/list` виглядали як зависання
# на дві хвилини замість «HTTP 404 за 0.2 с». Повтор має сенс лише там, де
# наступна спроба може дати інший результат; 404 та мережева відмова іншого
# результату не дають без окремої ознаки таймауту.
# Реалізація переїхала в `lib/Http/Client.php`; цей файл лишається сумісним
# швом для 17 викликачів і не змінює їхньої форми аргументів.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
readonly ROOT

exec php "$ROOT/cli/api/http-client.php" "$@"
