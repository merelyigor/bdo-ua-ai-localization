#!/usr/bin/env bash
# PATH для набору, запущеного НЕ з термінала.
#
# Навіщо. Значок у Dock, ярлик, `launchd`, cron · усі вони стартують процес
# через LaunchServices, а той дає мінімальний `PATH`:
#
#   /usr/bin:/bin:/usr/sbin:/sbin
#
# Homebrew ставить `php` у `/opt/homebrew/bin`, і цієї теки там НЕМАЄ. Тому
# набір, який ідеально працює в терміналі, з-під значка вмирав на
# `command -v php` з написом «web: немає php» (виявлено власником 2026-09-06).
# Той самий мінімальний `PATH` ламав і `./bdo web --status`, тому значок навіть
# не бачив УЖЕ ПІДНЯТОГО інтерфейсу й ішов піднімати другий.
#
# Клас ширший за php: так само не знайшлися б `ollama`, `tmux`, `vhs`, `curl`
# з Homebrew. Тому лагодиться не одна команда, а сам `PATH`, і робиться це в
# `bdo` · єдиному вході. Кожен наступний кліковий вхід дістає це задарма.
#
# ЦІНА В ТЕРМІНАЛІ · НУЛЬ. Коли `php` уже видно (звичайний запуск, тести, CI),
# файл не робить нічого: жодного підпроцесу, жодної зміни оточення.
#
# Файл призначений для `source`, тому НЕ має біта виконання · як
# `cli/system/select-env.sh`.

if ! command -v php >/dev/null 2>&1; then
    # Джерелом правди є ЛОГІН-ОБОЛОНКА власника: саме її `PATH` бачить `./bdo`
    # у терміналі, де набір працює. Відтворювати її здогадом не можна ·
    # Homebrew буває в `/opt/homebrew`, `/usr/local`, а буває й у власній теці.
    #
    # Маркер обовʼязковий: файли `~/.zprofile` й `~/.zshrc` мають повне право
    # щось надрукувати, і без маркера цей друк став би частиною `PATH`.
    if [ -x "${SHELL:-}" ]; then
        # shellcheck disable=SC2016  # `$PATH` мусить розкритись У ТІЙ оболонці, не тут
        _bdo_out="$("$SHELL" -lc 'printf "\n<<BDO_PATH>>%s" "$PATH"' 2>/dev/null || true)"
        _bdo_path="${_bdo_out##*<<BDO_PATH>>}"
        case "$_bdo_path" in
            "$_bdo_out") ;;          # маркера немає · оболонка нічого не дала
            /*) PATH="$_bdo_path:$PATH" ;;
        esac
        unset _bdo_out _bdo_path
    fi

    # Запасний шлях. Логін-оболонка могла не спрацювати (SHELL не заданий,
    # `-lc` заборонений політикою, профіль впав). Тоді беремо типові місця ·
    # це здогад, і саме тому він ДРУГИЙ, а не перший.
    for _bdo_dir in /opt/homebrew/bin /usr/local/bin /opt/local/bin "$HOME/.local/bin"; do
        test -d "$_bdo_dir" || continue
        case ":$PATH:" in
            *":$_bdo_dir:"*) ;;
            *) PATH="$PATH:$_bdo_dir" ;;
        esac
    done
    unset _bdo_dir

    export PATH
fi
