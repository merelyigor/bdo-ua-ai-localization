#!/usr/bin/env bash
# Значок у Dock: поки він живий · живий і інтерфейс. Закрив значок · зупинився.
#
# Навіщо. Для Windows такий місток уже є (`bdo.bat`), і там закриття вікна гасить
# сервер саме тому, що він тримається того вікна. Власник попросив те саме на
# macOS (2026-09-06): перетягнути значок у Dock, клікнути · відкрилось,
# закрити значок · зупинилось.
#
# ТОМУ ЦЕЙ ПРОЦЕС НЕ ЗАВЕРШУЄТЬСЯ ОДРАЗУ. Він піднімає сервер, відкриває
# браузер і ЧЕКАЄ. Вихід із додатка (Cmd+Q, «Завершити» в Dock, вимкнення
# компʼютера) надсилає сигнал, і пастка гасить сервер. Якби додаток просто
# стартував і зникав, у Dock не було б чого закривати · і зупинка не мала б
# жодного звʼязку зі значком.
#
# Логіка живе ТУТ, а не в бандлі: усередині `BDO.app` її не бачать ні
# `bash -n`, ні ShellCheck, ні gate.
#
# ЧОМУ БАНДЛ МУСИТЬ ЛИШАТИСЬ У ТЕЦІ НАБОРУ. Шлях до набору береться від
# розташування самого файла. Dock тримає посилання на оригінал, тому
# перетягування працює; КОПІЯ кудись інде втратить набір, і про це скаже вікно
# (пояснення живе в самому містку · іншого коду там уже не буде).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
readonly SCRIPT_DIR

# Діалог macOS. Без термінала `echo` нікуди не веде: додаток запускають кліком,
# і єдина видима поверхня · вікно системи.
say() {   # <текст> [опції osascript…]
    local text="$1"
    shift
    if command -v osascript >/dev/null 2>&1; then
        osascript -e "display dialog \"${text//\"/\\\"}\" with title \"BDO Локалізація\" $*" 2>/dev/null
    else
        printf '%s\n' "$text"
    fi
}

test -x "$SCRIPT_DIR/bdo" || {
    say "Набір не знайдено поруч із додатком." 'buttons {"Зрозуміло"} default button 1' >/dev/null || true
    exit 1
}
cd "$SCRIPT_DIR"

status_url() {
    ./bdo web --status 2>/dev/null | sed -n 's~.*\(http://127\.0\.0\.1:[0-9]*/?t=[0-9a-f]*\).*~\1~p' | head -1
}

# ЗУПИНКА РІВНО ОДИН РАЗ. Пастка спрацьовує і на сигнал, і на звичайний вихід,
# тому без цього прапорця `./bdo web --stop` кликався б двічі.
STOPPED=0
# shellcheck disable=SC2329  # кличеться з `trap`, статичний аналіз цього не бачить
stop_web() {
    test "$STOPPED" = 0 || return 0
    STOPPED=1
    ./bdo web --stop >/dev/null 2>&1 || true
}
trap 'stop_web; exit 0' INT TERM HUP
trap 'stop_web' EXIT

# ЗНАЧОК ПЕРЕХОПЛЮЄ СЕРВЕР БЕЗ ПИТАНЬ · вимога власника 2026-09-06.
#
# Раніше тут стояло вікно з вибором «Взяти під значок» чи «Просто відкрити»,
# і воно було помилкою двічі. По суті: значок є ПУЛЬТОМ інтерфейсу, а не ще
# одним його запускачем · кому належить сервер, власника не цікавить. І по
# формі: кнопкою за замовчуванням була саме та, що ЗАКРИВАЛА додаток, тож
# Enter гасив значок замість того, щоб лишити його відкритим.
#
# Наслідок названий прямо, бо він реальний: закриття значка зупиняє й той
# інтерфейс, який підняли з термінала. Це і є «керувати сервером».
URL="$(status_url || true)"
if [ -z "$URL" ]; then
    if ! out="$(./bdo web --background --no-open 2>&1)"; then
        trap - EXIT
        # «немає php» з-під значка майже завжди означає не відсутній php, а
        # PATH без Homebrew (D89). Це лагодить `cli/system/gui-path.sh`, тому
        # напис тут ще й каже, що саме зламалось, якщо він усе-таки вигулькнув.
        case "$out" in
            *'немає php'*) out="$out

PATH клікового запуску не бачить php. Перевірка: ./bdo gate shell" ;;
        esac
        say "Не вдалося підняти інтерфейс.

$out" 'buttons {"Зрозуміло"} default button 1' >/dev/null || true
        exit 1
    fi
    URL="$(status_url || true)"
    if [ -z "$URL" ]; then
        say "Сервер стартував, але посилання не знайдено: ./bdo web --status" \
            'buttons {"Зрозуміло"} default button 1' >/dev/null || true
        exit 1
    fi
fi

# Один вихід на обидві гілки: підняли ми сервер чи перехопили чужий · власник
# бачить те саме вікно браузера.
open "$URL" 2>/dev/null || true

# Тримаємо додаток живим, поки живий сервер. Опитування раз на дві секунди
# коштує нуль (читання файла стану), а `wait` тут неможливий: сервер
# запущений відвʼязаним і не є нашою дитиною.
#
# Сервер зупинили інакше (термінал, `make web-stop`) · значок теж зникає, а не
# висить у Dock, обіцяючи роботу, якої немає.
while [ -n "$(status_url || true)" ]; do
    sleep 2
done
trap - EXIT
exit 0
