#!/usr/bin/env bash
# Виміряти крок і записати мітку · не змінюючи його поведінки.
#
#   timed.sh <імʼя-кроку> <команда> [аргументи…]
#
# Обгортка НЕ ковтає нічого: stdout і stderr ідуть як були, код виходу
# повертається як був. Інакше вимірювання саме стало б джерелом тихих збоїв ·
# рівно того класу, проти якого існує §12.
#
# Навіщо взагалі. Розриви між пачками (173 і 259 с) виглядали як накладні
# витрати конвеєра · мітки показали, що це були паузи між ОКРЕМИМИ запусками
# `--batches 1`, а не робота набору. У неперервному прогоні на дві пачки решта
# кроків важить 11% часу, а не третину. Заяву такого роду без міток неможливо
# ні довести, ні спростувати · тому вони й існують.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
STEP="${1:?Потрібне імʼя кроку}"
shift || true
test "$#" -gt 0 || { printf 'timed: немає команди для виміру кроку «%s»\n' "$STEP" >&2; exit 2; }

# Імʼя кроку йде в журнал, який читає екран власника · довільний рядок туди не
# пускаємо.
case "$STEP" in
    *[!a-z_.-]*) printf 'timed: імʼя кроку «%s» містить недозволені символи\n' "$STEP" >&2; exit 2 ;;
esac

# Час беремо ВБУДОВАНИМ `$EPOCHREALTIME`, а не окремим процесом php.
#
# D81: перша редакція питала час у php ДВІЧІ на крок. Під час живого прогону
# 2026-09-05, коли в памʼяті лежала модель на 23 ГБ, другий виклик не піднявся,
# і `set -e` убив обгортку ще до запису мітки. Драйвер побачив ненульовий код і
# зупинив пачку словами «роль translation-judge не дала відповіді» · хоча роль
# ВІДПОВІЛА (`verdict=ok`, 51.2 с у журналі викликів). Тобто вимірювання вбило
# роботу, яку міряло, і збрехало про причину.
#
# Роздільник дробової частини залежить від локалі (`1788635953,195271`), тому
# ріжемо по обох варіантах. `10#` знімає вісімкове тлумачення нулів.
now_ms() {
    local raw="${EPOCHREALTIME:-}"
    if [ -n "$raw" ]; then
        local sec="${raw%%[.,]*}" frac="${raw##*[.,]}"
        frac="${frac}000"
        printf '%s' "$(( 10#$sec * 1000 + 10#${frac:0:3} ))"
        return 0
    fi
    # bash без `$EPOCHREALTIME` · секундна точність замість жодної.
    printf '%s' "$(( SECONDS * 1000 ))"
}

START_MS="$(now_ms)"
set +e
"$@"
CODE=$?
set -e
END_MS="$(now_ms)"

# Мітка пишеться ЗАВЖДИ, і на відмові теж: крок, що впав через 90 секунд,
# коштує стільки ж часу, як успішний.
# Запис мітки НЕ має права змінити долю кроку · тому вся гілка під `|| true`,
# і код виходу повертається той самий, що дала команда (D81).
php -r '
require $argv[1];
(new Bdo\Translate\Run\StepTimes($argv[2]))->record($argv[3], (int) $argv[4], (int) $argv[5]);
' "$SCRIPT_DIR/lib/autoload.php" \
  "${BDO_STATE_DIR:-$SCRIPT_DIR/state}" \
  "$STEP" "$(( END_MS >= START_MS ? END_MS - START_MS : 0 ))" "$CODE" 2>/dev/null || true

exit "$CODE"
