<?php

declare(strict_types=1);

namespace Bdo\Translate\Model\Transport;

/**
 * Транспорт до провайдера моделі.
 *
 * Контракт свідомо вузький: один виклик, одна зібрана відповідь. Усе, що
 * стосується ЗМІСТУ (валідність JSON, порожня відповідь, обрив, схема,
 * identity), лишається в клієнті · транспорт відповідає лише за протокол.
 *
 * Обидва відомі протоколи РЯДКОВІ (Ollama · NDJSON, OpenAI · SSE `data:`),
 * тому читач один, а розбір рядка · за провайдером.
 */
interface Transport
{
    /**
     * Виконати виклик.
     *
     * @param  callable(string,bool):void|null  $onChunk  шматок тексту й ознака
     *         «це роздуми»; викликається в міру надходження, коли є потік
     *
     * @throws TransportError коли протокол не дав відповіді
     */
    public function send(Request $request, ?callable $onChunk = null): Reply;

    /**
     * Реальне вікно контексту моделі, якщо провайдер його повідомляє.
     *
     * Нуль означає «невідомо», і це НЕ помилка: у зовнішніх API вікна не
     * запитати, тому перевірка тихого обрізання входу там просто не робиться.
     * Мовчати про це не можна · клієнт мусить бачити різницю між «вікно велике»
     * і «вікно невідоме».
     */
    public function window(string $model): int;

    /** Імʼя для журналу й повідомлень: `ollama`, `openai`. */
    public function name(): string;
}
