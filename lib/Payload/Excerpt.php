<?php

declare(strict_types=1);

namespace Bdo\Translate\Payload;

/**
 * Уривок навколо терміна · замість повного опису предмета.
 *
 * Навіщо. Термінолог отримує ОДИН запис на кожен термін, і в кожному лежав
 * ПОВНИЙ `source_text` рядка, де термін трапився. Заміряно 2026-09-06 на
 * живому прогоні: 136 термінів дали payload 111 КБ, `in=43 839` токенів,
 * `out=17 722`, 621 секунду · найважчий виклик усього флоу, більший за воркер
 * і QA разом. Описи предметів BDO довгі, а термінологу потрібне не все опис, а
 * місце, де слово вжите: саме воно каже, це назва предмета чи дієслово в прозі.
 *
 * Правило: беремо вікно навколо ПЕРШОЇ згадки терміна. Не знайшли дослівно
 * (відмінок, інший регістр) · беремо початок тексту, бо він майже завжди несе
 * назву. Обрізаний край позначаємо трикрапкою: модель мусить бачити, що це
 * фрагмент, а не повний рядок.
 */
final class Excerpt
{
    /** Скільки символів віддавати навколо терміна · разом із самим терміном. */
    public const DEFAULT_BUDGET = 240;

    public static function around(string $text, string $term, ?int $budget = null): string
    {
        $limit = $budget ?? self::DEFAULT_BUDGET;
        if ($limit <= 0 || mb_strlen($text) <= $limit) {
            return $text;
        }
        $at = $term === '' ? false : mb_stripos($text, $term);
        if ($at === false) {
            return mb_substr($text, 0, $limit).'…';
        }
        // Термін ставимо ближче до середини вікна: контекст потрібен з обох
        // боків · «Move» у назві кнопки й «move» у реченні виглядають однаково,
        // а означають різне.
        $half = (int) max(0, ($limit - mb_strlen($term)) / 2);
        $from = max(0, $at - $half);
        $piece = mb_substr($text, $from, $limit);

        return ($from > 0 ? '…' : '').$piece.($from + $limit < mb_strlen($text) ? '…' : '');
    }
}
