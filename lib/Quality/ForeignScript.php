<?php

declare(strict_types=1);

namespace Bdo\Translate\Quality;

/**
 * Символи чужої писемності в українському перекладі.
 *
 * Навіщо. 2026-08-27 власник поставив локальну збірку
 * `lucloner/wen36-35b-uncensored-1m:mtp` і вона вставляла в український текст
 * китайські ієрогліфи. Жодна наявна перевірка цього не бачила: `Homoglyphs`
 * шукає ЛАТИНСЬКІ двійники кирилиці, `Russianisms` · російські слова й літери.
 * Ієрогліф не є ні тим, ні тим, тому рядок ішов у ШІ-шар як валідний.
 *
 * Клас ширший за одну модель. Курс проєкту · локальні квантизовані моделі
 * (70-80% дитячих сесій), а вони зриваються в мову тренувального корпусу
 * частіше за хмарні. Правило описується правилом, отже місце йому в коді, а не
 * в проханні всередині промпта.
 *
 * Межа хибних спрацювань. Символ, який Є у вихідному тексті рядка, дефектом не
 * вважається: гра корейська, і назва з ієрогліфом у джерелі законна · її треба
 * зберегти, а не вирізати.
 */
final class ForeignScript
{
    /**
     * Діапазони, яких в українському перекладі бути не може.
     *
     * Латиниця, кирилиця, цифри, розділові знаки й типографіка сюди НЕ входять
     * навмисно: латиниця легальна (`Black Desert`, теґи, placeholders), а
     * кирилиця перевіряється іншими детекторами.
     *
     * @var array<string,string> регулярний клас => назва писемності
     */
    private const SCRIPTS = [
        '\x{4E00}-\x{9FFF}\x{3400}-\x{4DBF}' => 'китайські ієрогліфи',
        '\x{3040}-\x{309F}\x{30A0}-\x{30FF}' => 'японська кана',
        '\x{AC00}-\x{D7AF}\x{1100}-\x{11FF}' => 'корейський хангиль',
        '\x{0600}-\x{06FF}\x{0750}-\x{077F}' => 'арабиця',
        '\x{0590}-\x{05FF}' => 'іврит',
        '\x{0E00}-\x{0E7F}' => 'тайська',
        '\x{0900}-\x{097F}' => 'деванагарі',
        '\x{0370}-\x{03FF}' => 'грека',
    ];

    /**
     * @param  string  $source  вихідний текст рядка; символ звідти не є дефектом
     * @return list<array{word:string,script:string}>
     */
    public static function find(string $text, string $source = ''): array
    {
        $found = [];
        foreach (self::SCRIPTS as $class => $script) {
            if (preg_match_all('/['.$class.']+/u', $text, $matches) < 1) {
                continue;
            }
            foreach ($matches[0] as $chunk) {
                if ($source !== '' && mb_strpos($source, $chunk) !== false) {
                    continue;
                }
                $found[] = ['word' => $chunk, 'script' => $script];
            }
        }

        return $found;
    }
}
