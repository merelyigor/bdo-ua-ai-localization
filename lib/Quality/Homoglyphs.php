<?php

declare(strict_types=1);

namespace Bdo\Translate\Quality;

/**
 * Латинські гомогліфи всередині кириличних слів.
 *
 * Модель регулярно пише латинську `E` в українському слові: `Eданa` замість
 * `Едана`. Візуально різниці немає, але це інший символ - ламається пошук,
 * сортування й порівняння з глосарієм. На живій пачці 2026-08-16 таких рядків
 * було 14 з 20, і QA справедливо позначив усі як REVIEW.
 *
 * ПРАВИЛО РОЗПІЗНАВАННЯ: дефект - це слово, у якому ЗМІШАНІ кирилиця й
 * латиниця. Суто латинське слово (`HAN`, `Everlight`, `AP`) - не дефект: такі
 * назви навмисно лишаються латиницею, вони є в 27% машинних і майже половині
 * ручних перекладів. Саме тому не можна просто заборонити латиницю.
 *
 * Виправлення детерміноване, тому робиться кодом, а не моделлю: у змішаному
 * слові латинські літери замінюються кириличними двійниками.
 */
final class Homoglyphs
{
    /** Латинська літера => кирилична, візуально ідентична. */
    private const MAP = [
        'A' => 'А', 'B' => 'В', 'C' => 'С', 'E' => 'Е', 'H' => 'Н', 'I' => 'І',
        'K' => 'К', 'M' => 'М', 'O' => 'О', 'P' => 'Р', 'T' => 'Т', 'X' => 'Х',
        'Y' => 'У',
        'a' => 'а', 'c' => 'с', 'e' => 'е', 'i' => 'і', 'o' => 'о', 'p' => 'р',
        'x' => 'х', 'y' => 'у',
    ];

    /**
     * Цифри, візуально невідрізнні від кириличних літер у слові.
     *
     * Окремо від латиниці, бо цифра в тексті НОРМАЛЬНА: `50%`, `3 рівень`,
     * `Тир 4`. Двійником вона стає лише там, де стоїть НА МІСЦІ літери:
     * `3броя`, `0бладунки`, `4ерепаха`.
     *
     * Умова навмисно вужча за «цифра поруч із кирилицею». Перша версія ловила
     * `Рівень1`, `Скриня3` і `Тир4`, тобто нумерацію без пробілу · цілком
     * законний текст. Тому цифра рахується двійником, лише коли вона стоїть на
     * ПОЧАТКУ слова перед кирилицею або МІЖ двома кириличними літерами; цифра в
     * кінці слова не рахується ніколи.
     *
     * `1` у переліку немає свідомо: він однаково схожий на `І` та `l`, а
     * найчастіше є просто номером.
     *
     * Додано 2026-08-27 після аудиту семи механічних перевірок: `3броя`
     * проходило як чисте, бо цифра не є латинською літерою.
     */
    private const DIGITS = ['3' => 'З', '0' => 'О', '6' => 'б', '4' => 'ч'];

    /**
     * Кирилична літера => латинське написання, яким її транслітерують.
     *
     * Таблиця служить ЛИШЕ для порівняння зіпсованого слова з оригіналом, а не
     * для перекладу: результат нікуди не потрапляє, крім рівності двох кістяків.
     */
    private const TRANSLIT = [
        'а' => 'a', 'б' => 'b', 'в' => 'v', 'г' => 'h', 'ґ' => 'g', 'д' => 'd',
        'е' => 'e', 'є' => 'ye', 'ж' => 'zh', 'з' => 'z', 'и' => 'y', 'і' => 'i',
        'ї' => 'yi', 'й' => 'y', 'к' => 'k', 'л' => 'l', 'м' => 'm', 'н' => 'n',
        'о' => 'o', 'п' => 'p', 'р' => 'r', 'с' => 's', 'т' => 't', 'у' => 'u',
        'ф' => 'f', 'х' => 'h', 'ц' => 'ts', 'ч' => 'ch', 'ш' => 'sh',
        'щ' => 'shch', 'ь' => '', 'ю' => 'yu', 'я' => 'ya',
    ];

    /**
     * Слова зі змішаними абетками.
     *
     * Повертає ВСІ такі слова, зокрема ті, які код виправити не може.
     *
     * Раніше умова була `$fixed !== $word`, тобто детектор бачив лише те, що
     * вмів полагодити. 2026-08-28 на живій пачці рядок `Sаmоtня альтанка серед
     * природи.` пройшов механіку як чистий: латинські `S` і `m` кириличних
     * двійників не мають, тому слово не змінювалось · і зникало зі списку разом
     * із латинськими `а` та `о`, які двійників мають. Зловила його вже модель
     * QA, тобто випадково: механічний дефект опинився нижче судді.
     *
     * Виявлення й виправлення розділені: `fixed` може дорівнювати `word`, і це
     * означає «дефект є, автоматичного виправлення немає» · такий рядок іде в
     * repair, а не в шар.
     *
     * `$source` дозволяє слово, яке дослівно є в оригіналі: там змішана абетка
     * є даними гри, а не зривом моделі.
     *
     * @return list<array{word:string,fixed:string}>
     */
    public static function find(string $text, string $source = ''): array
    {
        $found = [];
        foreach (self::words($text) as $word) {
            if (! self::isMixed($word)) {
                continue;
            }
            if ($source !== '' && str_contains($source, $word)) {
                continue;
            }
            $found[] = [
                'word' => $word,
                'fixed' => self::restoreFromSource($word, $source) ?? self::fixWord($word),
            ];
        }

        return $found;
    }

    /**
     * Замінити латинські двійники в змішаних словах. Решту тексту не чіпає.
     *
     * `$source` обовʼязковий для відновлення недописаної транслітерації: без
     * оригіналу код бачить лише двійники й не знає правильного написання
     * назви. Тому нормалізація кандидата передає сюди текст джерела.
     */
    public static function fix(string $text, string $source = ''): string
    {
        foreach (self::find($text, $source) as $hit) {
            $text = str_replace($hit['word'], $hit['fixed'], $text);
        }

        return $text;
    }

    /** @return list<string> */
    private static function words(string $text): array
    {
        // Цифри входять у «слово»: `3броя` мусить бути одним словом, інакше
        // цифровий двійник не має кириличного сусіда й не помічається.
        preg_match_all('/[\p{L}0-9]+/u', $text, $m);

        return $m[0] ?? [];
    }

    private static function isMixed(string $word): bool
    {
        if (preg_match('/\p{Cyrillic}/u', $word) !== 1) {
            return false;
        }
        if (preg_match('/[A-Za-z]/', $word) === 1) {
            return true;
        }

        // Цифра рахується двійником лише СЕРЕД кирилиці: `3броя` є дефектом,
        // `Тир 4` і `50%` · ні. Слово тут уже виділене як послідовність літер і
        // цифр, тому достатньо перевірити, що цифра має кириличного сусіда.
        return preg_match(self::digitPattern(), $word) === 1;
    }

    /** Цифра на початку слова перед кирилицею або між двома кириличними. */
    private static function digitPattern(): string
    {
        $digits = implode('', array_keys(self::DIGITS));

        return '/^['.$digits.'](?=\p{Cyrillic})|(?<=\p{Cyrillic})['.$digits.'](?=\p{Cyrillic})/u';
    }

    /**
     * Недописана транслітерація власної назви: повернути написання з оригіналу.
     *
     * Клас знайдено виміром 2026-09-21: `Illezra` доходило до фінального
     * тексту як `Ілlezra` · модель почала транслітерувати назву кирилицею й
     * кинула на середині слова. Заміна латинських двійників кириличними тут
     * НЕ ПОМАГАЄ і робить гірше: `l`, `z`, `r` кириличних двійників не мають,
     * тому `fixWord()` віддавав так само змішане `Ілlеzrа`, ремонт не міг
     * закрити дефект жодною спробою, і рядок ішов до людини. У пачці
     * `20260921_114432` таких було 6 із 20.
     *
     * Правильна відповідь лежить в ОРИГІНАЛІ: якщо прибрати різницю абеток,
     * зіпсоване слово збігається з токеном джерела дослівно. Відповідність
     * вимагається ТОЧНА і ЄДИНА · назва береться з даних, а не вигадується.
     * Відмінена форма (`Ілlezрі`) збігу не дає й лишається ремонту.
     *
     * Вимірено на 60 рядках із дефектом абетки: 33 закриваються цим кодом
     * повністю, без жодного виклику моделі.
     */
    private static function restoreFromSource(string $word, string $source): ?string
    {
        if ($source === '') {
            return null;
        }
        $skeleton = self::skeleton($word);
        if ($skeleton === '') {
            return null;
        }
        preg_match_all('/[\p{L}0-9]+/u', $source, $m);
        $match = null;
        foreach ($m[0] ?? [] as $token) {
            if ($token === $word || preg_match('/\p{Cyrillic}/u', $token) === 1) {
                continue;
            }
            if (self::skeleton($token) !== $skeleton) {
                continue;
            }
            if ($match !== null && $match !== $token) {
                // Два різні токени з тим самим кістяком · вибір неоднозначний,
                // а вгадувати назву заборонено.
                return null;
            }
            $match = $token;
        }

        return $match;
    }

    /** Написання без різниці абеток: кирилиця зводиться до латиниці. */
    private static function skeleton(string $word): string
    {
        $out = '';
        foreach (preg_split('//u', $word, -1, PREG_SPLIT_NO_EMPTY) ?: [] as $char) {
            $lower = mb_strtolower($char, 'UTF-8');
            $out .= self::TRANSLIT[$lower] ?? $lower;
        }

        return $out;
    }

    private static function fixWord(string $word): string
    {
        $fixed = strtr($word, self::MAP);

        // Замінюємо лише ті цифри, що стоять поруч із кирилицею: інакше
        // `Тир 4` перетворилось би на `Тир ч`.
        return (string) preg_replace_callback(
            self::digitPattern(),
            static fn (array $m): string => self::DIGITS[$m[0]] ?? $m[0],
            $fixed,
        );
    }
}
