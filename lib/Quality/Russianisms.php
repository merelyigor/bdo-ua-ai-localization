<?php

declare(strict_types=1);

namespace Bdo\Translate\Quality;

use Bdo\Translate\Batch\Row;

/**
 * Словниковий детектор русизмів.
 *
 * Перевірка за російськими літерами (ы, э, ъ, ё) ловить лише частину випадків.
 * Найнебезпечніші русизми пишуться українськими буквами й проходять повз неї:
 * на живому прогоні модель видала «Камень пересікування» у шести рядках, а
 * літерна перевірка показала нуль дефектів.
 *
 * ПРІОРИТЕТ ГЛОСАРІЮ. Затверджений канонічний відповідник завжди сильніший за
 * цей словник. Якщо глосарій рядка каже «Доспехи Жарів Іксіна», перекладач
 * зобовʼязаний написати саме так, і детектор не має права це блокувати -
 * інакше механіка вимагала б порушити канон. Ревізія таких термінів - робота
 * в самому глосарії, а не в перевірці пачки.
 */
final class Russianisms
{
    /** Російські літери - незалежна від словника ознака. */
    private const RUSSIAN_LETTERS = '/[ыэъё]/iu';

    /**
     * Ключ - фрагмент регулярного виразу, застосовується як `/\b<ключ>\b/iu`.
     *
     * Суфікс `\w*` пишеться ЯВНО там, де русизм має відмінюватись. Це не
     * косметика: неявний `\w*` для всіх записів дав хибне спрацювання на живому
     * прогоні - стем `камен(ь|я|ю)` заклеймив українську «Каменюку», а форми
     * «каменя», «каменю» взагалі є нормою української. Русизмом є лише
     * називний «камень».
     *
     * Тут лише слова з однозначним українським відповідником: хибне
     * спрацювання блокує добрий переклад, а це дорожче за пропущений випадок.
     *
     * @return array<string,string> шаблон => український відповідник
     */
    public static function dictionary(): array
    {
        return [
            'сумерк\w*' => 'сутінки',
            'серьг\w*' => 'сережка',
            'серга' => 'сережка',
            'серги' => 'сережки',
            'доспех\w*' => 'обладунки',
            'осколок' => 'уламок',
            'осколк(а|и|ів|ом|у)' => 'уламок',
            'перчатк\w*' => 'рукавиці',
            'сапог\w*' => 'чоботи',
            'мешок' => 'мішок',
            'мешк(а|и|ів|ом|у)' => 'мішок',
            'сундук\w*' => 'скриня',
            'бумаг\w*' => 'папір',
            'краск(а|и|ою|у)' => 'фарба',
            'стрела' => 'стріла',
            'стрелы' => 'стріли',
            'щит[оы]' => 'щит',
            'кольцо' => 'перстень',
            'кольца' => 'персні',
            'пояс(ниц|ок)\w*' => 'пояс',
            'напиток' => 'напій',
            'напитк(а|и|ів|ом|у)' => 'напій',
            'оруж\w*' => 'зброя',
            'камень' => 'камінь',
            'цветок' => 'квітка',
            'цветк(а|и|ом|у)' => 'квітка',
            'деревянн\w*' => 'дерев\'яний',
            'железн\w*' => 'залізний',
            'золот(ой|ая|ое|ые)' => 'золотий',
            'серебр\w*' => 'срібло',
            'улучшен\w*' => 'покращення',
            'усилен\w*' => 'посилення',
            'прочност\w*' => 'міцність',
            'износ' => 'знос',
            'награда' => 'нагорода',
            'задани(е|я|ю|ем)' => 'завдання',
            'умени(е|я|ю|ем)' => 'уміння',
            'способност\w*' => 'здібність',
        ];
    }

    /**
     * Шаблони, які легалізує затверджений глосарій рядка.
     *
     * Береться лише непорожній `ukrainian`: термін зі severity=mandatory і
     * ukrainian=null нічого не затверджує й нічого не легалізує.
     *
     * @return list<string>
     */
    public static function allowedByGlossary(Row $row): array
    {
        $allowed = [];
        foreach ($row->glossary() as $ukrainian) {
            foreach (array_keys(self::dictionary()) as $pattern) {
                if (preg_match('/\b'.$pattern.'\b/iu', $ukrainian) === 1) {
                    $allowed[$pattern] = true;
                }
            }
            if (preg_match(self::RUSSIAN_LETTERS, $ukrainian) === 1) {
                $allowed[self::RUSSIAN_LETTERS] = true;
            }
        }

        return array_keys($allowed);
    }

    /**
     * Знайти русизми в тексті.
     *
     * @param  list<string>  $allowedPatterns  легалізоване глосарієм цього рядка
     * @return list<array{word:string,suggest:string}>
     */
    public static function find(string $text, array $allowedPatterns = []): array
    {
        $allowed = array_flip($allowedPatterns);
        $found = [];
        foreach (self::dictionary() as $pattern => $suggest) {
            if (isset($allowed[$pattern])) {
                continue;
            }
            if (preg_match('/\b'.$pattern.'\b/iu', $text, $m) === 1) {
                $found[] = ['word' => $m[0], 'suggest' => $suggest];
            }
        }
        if (! isset($allowed[self::RUSSIAN_LETTERS]) && preg_match(self::RUSSIAN_LETTERS, $text, $m) === 1) {
            $found[] = ['word' => $m[0], 'suggest' => 'російська літера'];
        }

        return $found;
    }

    /**
     * Русизми з урахуванням глосарію рядка.
     *
     * @return list<array{word:string,suggest:string}>
     */
    public static function findInRow(Row $row, string $text): array
    {
        return self::find($text, self::allowedByGlossary($row));
    }
}
