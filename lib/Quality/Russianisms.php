    /**
     * Шаблони, які легалізує затверджений глосарій рядка.
     *
     * Береться лише непорожній `ukrainian`: термін зі severity=mandatory і
     * ukrainian=null нічого не затверджує й нічого не легалізує.
     *
     * @return list<string>
     */
    public static function allowedByGlossary(Row $row): array
    {
        $allowed = [];
        foreach ($row->glossary() as $ukrainian) {
            foreach (array_keys(self::dictionary()) as $pattern) {
                if (preg_match('/\b'.$pattern.'\b/iu', $ukrainian) === 1) {
                    $allowed[$pattern] = true;
                }
            }
            if (preg_match(self::RUSSIAN_LETTERS, $ukrainian) === 1) {
                $allowed[self::RUSSIAN_LETTERS] = true;
            }
        }

        return array_keys($allowed);
    }

    /**
     * Знайти русизми в тексті.
     *
     * @param  list<string>  $allowedPatterns  легалізоване глосарієм цього рядка
     * @return list<array{word:string,suggest:string}>
     */
    public static function find(string $text, array $allowedPatterns = []): array
    {
        $allowed = array_flip($allowedPatterns);
        $found = [];
        foreach (self::dictionary() as $pattern => $suggest) {
            if (isset($allowed[$pattern])) {
                continue;
            }
            if (preg_match('/\b'.$pattern.'\b/iu', $text, $m) === 1) {
                $found[] = ['word' => $m[0], 'suggest' => $suggest];
            }
        }
        if (! isset($allowed[self::RUSSIAN_LETTERS]) && preg_match(self::RUSSIAN_LETTERS, $text, $m) === 1) {
            $found[] = ['word' => $m[0], 'suggest' => 'російська літера'];
        }

        return $found;
    }

    /**
     * Русизми з урахуванням глосарію рядка.
     *
     * @return list<array{word:string,suggest:string}>
     */
    public static function findInRow(Row $row, string $text): array
    {
        return self::find($text, self::allowedByGlossary($row));
    }
}
