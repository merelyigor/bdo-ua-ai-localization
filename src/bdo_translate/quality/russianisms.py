def russianism_hits(text: str, allowed: set[str]) -> list[tuple[str, str]]:
    """Повертає перше входження кожного не дозволеного русизму."""
    found: list[tuple[str, str]] = []
    for pattern, hint in RUSSIANISMS.items():
        if any(
            regex.search(rf"\b{pattern}\b", approved, regex.IGNORECASE) is not None
            for approved in allowed
        ):
            continue
        match = regex.search(rf"\b{pattern}\b", text, regex.IGNORECASE)
        if match is not None:
            found.append((match.group(), hint))

    if not any(regex.search(RUSSIAN_LETTERS, approved, regex.IGNORECASE) for approved in allowed):
        match = regex.search(RUSSIAN_LETTERS, text, regex.IGNORECASE)
        if match is not None:
            found.append((match.group(), "російська літера"))
    return found
