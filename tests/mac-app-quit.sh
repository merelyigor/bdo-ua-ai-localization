#!/usr/bin/env bash
# Значок є ПУЛЬТОМ інтерфейсу: він лишається відкритим, поки живий сервер, і
# гасить сервер, коли його закривають. Обидва боки · вимога власника
# 2026-09-06, і обидва перевіряються тут на справжньому процесі, а не читанням
# тексту скрипта.
#
# Перевіряються три підкоманди, якими значок і живе:
#   `start` · підняти сервер або ПЕРЕХОПИТИ піднятий не ним (термінал,
#             `make web`). Перехоплення було зламане: гілка питала вікном, а
#             кнопкою за замовчуванням стояла та, що закривала додаток (D90);
#   `alive` · це питає `on idle` раз на дві секунди; ненульовий код прибирає
#             значок із Dock, тому обидва його стани важать однаково;
#   `stop`  · це робить `on quit`, тобто «Завершити» в Dock і Cmd+Q.
#
# САМ БАНДЛ тут не запускається: LaunchServices не передає застосунку оточення,
# тому запуск `BDO.app` пішов би в СПРАВЖНІЙ `state/` і зупинив живий інтерфейс
# власника. Те, що бандл є applet-ом і має `on quit`/`on idle`, перевіряє
# `./bdo gate shell` розкомпілюванням.
#
# ІЗОЛЯЦІЯ ОБОВʼЯЗКОВА. `mac-app.sh` кличе справжній `./bdo web --stop`, тому
# без власної теки стану й власного порту тест убив би ЖИВИЙ інтерфейс
# власника. `open` теж підмінено · інакше кожен запуск відкривав би вкладку.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
fail() { printf 'FAIL: %s\n' "$1" >&2; exit 1; }

test "$(uname -s)" = Darwin || { printf 'mac app quit: SKIP · не macOS\n'; exit 0; }
command -v php >/dev/null 2>&1 || fail 'немає php'

TMP="$(mktemp -d)"
cleanup() {
    BDO_STATE_DIR="$TMP/state" "$ROOT/bdo" web --stop >/dev/null 2>&1 || true
    rm -rf "$TMP"
}
trap cleanup EXIT

mkdir -p "$TMP/state" "$TMP/bin"
# Підмінений `open`: значок відкриває браузер, тесту це не потрібно.
printf '#!/usr/bin/env bash\nexit 0\n' >"$TMP/bin/open"
chmod +x "$TMP/bin/open"

export PATH="$TMP/bin:$PATH"
export BDO_STATE_DIR="$TMP/state"
export BDO_WEB_DEFAULT_PORT=$(( 46000 + RANDOM % 3000 ))

# `--status` виходить НУЛЕМ і тоді, коли сервера немає («Сервер не запущено»),
# тому питаємо те саме, що питає значок · посилання у виводі.
running() {
    "$ROOT/bdo" web --status 2>/dev/null \
        | grep -qE 'http://127\.0\.0\.1:[0-9]+/\?t='
}

wait_for() {   # <секунди> <«є»|«немає»>
    local limit="$1" want="$2" i=0
    while [ "$i" -lt $(( limit * 4 )) ]; do
        if running; then test "$want" = 'немає' || return 0
        else test "$want" = 'є' || return 0; fi
        sleep 0.25
        i=$(( i + 1 ))
    done
    return 1
}

app() { bash "$ROOT/cli/system/mac-app.sh" "$1"; }

# --- 1. `start` піднімає сервер сам -----------------------------------------
running && fail 'пісочниця вже має сервер · ізоляція не спрацювала'
app start >"$TMP/start.log" 2>&1 || fail "start упав: $(cat "$TMP/start.log")"
wait_for 40 'є' || fail "start не підняв сервер: $(cat "$TMP/start.log")"
grep -qE 'http://127\.0\.0\.1:[0-9]+/\?t=' "$TMP/start.log" \
    || fail 'start не надрукував посилання · applet не має що відкрити'

# --- 2. `alive` тримає значок у Dock ----------------------------------------
# Саме це `on idle` питає раз на дві секунди: код 0 · значок лишається.
app alive || fail 'alive каже «сервера немає» при живому сервері · значок зникне з Dock одразу'

# --- 3. `start` ПЕРЕХОПЛЮЄ вже піднятий сервер ------------------------------
# Найважливіша частина: сервер підняв не значок, і значок мусить його взяти,
# а не відмовитись і не підняти другий.
app start >"$TMP/adopt.log" 2>&1 || fail "start на живому сервері впав: $(cat "$TMP/adopt.log")"
running || fail 'start зупинив чужий сервер замість перехопити його'
grep -qE 'http://127\.0\.0\.1:[0-9]+/\?t=' "$TMP/adopt.log" \
    || fail 'перехоплення не віддало посилання'

# --- 4. `stop` гасить сервер ------------------------------------------------
# Це те, що робить `on quit` при «Завершити» в Dock і Cmd+Q.
app stop
wait_for 20 'немає' || fail 'stop НЕ зупинив інтерфейс · закриття значка лишить сервер жити'

# --- 5. `alive` без сервера мусить дати ненульовий код ----------------------
# Без цього значок висів би в Dock, обіцяючи роботу, якої немає.
if app alive; then fail 'alive каже «сервер є» при зупиненому сервері · значок завис би в Dock'; fi

# --- 6. Межа підкоманд ------------------------------------------------------
if app казна-що >/dev/null 2>&1; then fail 'mac-app.sh приймає невідому підкоманду'; fi

printf 'mac app quit: OK · start піднімає й перехоплює, alive тримає значок, stop гасить сервер.\n'
