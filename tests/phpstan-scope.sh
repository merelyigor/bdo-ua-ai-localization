#!/usr/bin/env bash
# СТАТИЧНИЙ АНАЛІЗ МУСИТЬ БАЧИТИ ВЕСЬ РОБОЧИЙ ШЛЯХ.
#
# До 2026-09-20 `phpstan.neon` перевіряв саму теку `lib`, а `cli/**` і
# entrypoint `bdo` · код, який і запускає прогін · не перевірявся нічим, крім
# `php -l`. Лінтер бачить лише синтаксис: помилка в імені класу, метода чи
# аргумента проходила б крізь нього мовчки й падала вже на живому прогоні.
#
# Тест робить дві речі. Спершу стереже ОБСЯГ · щоб жоден робочий PHP-файл не
# опинився поза переліком `paths`: звуження переліку є тихою відмовою, якої
# ніхто не помітить, бо прогін лишається зеленим · просто перевіряти стало
# нічого. Ця частина не вимагає жодного інструмента. Потім ганяє САМ аналіз,
# щоб помилка типів ловилась тут, а не після пушу в CI.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
fail() { printf 'FAIL: %s\n' "$1" >&2; exit 1; }

CONFIG='phpstan.neon'
test -f "$CONFIG" || fail "немає $CONFIG · статичного аналізу не існує взагалі"

# Перелік `paths:` читаємо з самого конфігу, а не переписуємо тут: інакше тест
# доводив би власну копію, а не те, що піде в CI.
paths="$(
    awk '
        /^[[:space:]]*paths:[[:space:]]*$/ { inside = 1; next }
        inside && /^[[:space:]]*-[[:space:]]*/ { sub(/^[[:space:]]*-[[:space:]]*/, ""); print; next }
        inside && /^[[:space:]]*[a-zA-Z_]+:/ { inside = 0 }
    ' "$CONFIG"
)"
test -n "$paths" || fail "у $CONFIG не знайдено жодного шляху аналізу"

# Рівень названий явно · без нього PHPStan мовчки візьме 0, і зміна рівня
# стала б невидимою. Нижче третього опускатись не можна: саме третій ловить
# звернення до неіснуючого поля й читання неоголошеної змінної, тобто класи,
# через які дефект доїжджає до живого прогону. Опустити рівень «щоб пройшло» ·
# це не виправлення, а приховування, тому межу стереже перевірка, а не звичай.
level="$(awk '/^[[:space:]]*level:[[:space:]]*[0-9]+/ { print $2; exit }' "$CONFIG")"
test -n "$level" || fail "у $CONFIG немає явного рівня аналізу"
test "$level" -ge 3 \
    || fail "рівень аналізу опущено до $level · нижче третього перевірка перестає ловити свій клас дефектів"

covered() {
    local file="$1" path
    for path in $paths; do
        case "$file" in
            "$path"|"$path"/*) return 0 ;;
        esac
    done
    return 1
}

# Робочий шлях · те, що виконується у власника. Оснастка розробки (`tests/**`,
# `scripts/**`) поза аналізом свідомо, і саме тому виняток названий ТУТ явним
# переліком: новий каталог робочого коду під нього не потрапить і завалить
# перевірку, а не проїде тихо.
uncovered=''
while IFS= read -r file; do
    case "$file" in
        tests/*|scripts/*|legacy/*) continue ;;
    esac
    covered "$file" || uncovered="$uncovered $file"
done <<EOF
$(git ls-files '*.php'; git ls-files | while IFS= read -r f; do
    case "$f" in *.*) continue ;; esac
    head -1 "$f" 2>/dev/null | grep -q 'env php' && printf '%s\n' "$f"
done)
EOF

test -z "$uncovered" \
    || fail "робочий PHP поза статичним аналізом ·$uncovered"

# Кожен названий шлях мусить існувати: неіснуючий рядок у переліку PHPStan
# вважає помилкою конфігурації, і CI впав би не на коді, а на друкарській
# помилці.
for path in $paths; do
    test -e "$path" || fail "у $CONFIG названо неіснуючий шлях: $path"
done

# CI мусить проганяти саме цей конфіг, а не власний перелік тек.
grep -Fq 'phpstan analyse -c phpstan.neon' .github/workflows/gate.yml \
    || fail 'CI не проганяє phpstan.neon · конфіг перестав бути джерелом правди'

# САМ АНАЛІЗ · ТУТ, А НЕ «КОЛИСЬ У CI». Типи · єдине, чого не бачить `php -l`,
# і дізнаватись про них після пушу означає ганяти CI замість роботи. Інструмент
# ставиться в систему (`brew install phpstan`) і в CI (`tools: phpstan`), тому
# його відсутність є подією, а не нормою · код 77 каже про це вголос.
if ! command -v phpstan >/dev/null 2>&1; then
    echo "phpstan scope: ПРОПУЩЕНО · немає phpstan, типи не перевірено (обсяг накриває ${paths//$'\n'/ })"
    exit 77
fi
# Межа памʼяті названа числом: аналіз іде паралельними процесами, і типові
# 128M у php.ini валили саме робітника, а виглядало це як поломка аналізатора.
phpstan analyse -c "$CONFIG" --no-progress --memory-limit=1G \
    || fail 'статичний аналіз знайшов помилки типів'

echo "phpstan scope: OK · аналіз накриває робочий шлях ($(printf '%s' "$paths" | tr '\n' ' ')) і проходить чисто"
