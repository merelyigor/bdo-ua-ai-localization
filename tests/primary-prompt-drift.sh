#!/usr/bin/env bash
# Спільна частина чотирьох primary-промптів мусить бути ОДНАКОВОЮ до символу.
#
# Клас дефекту. `патч`, `ручний`, `пропозиції` і `покращення-ші` мають ~90
# спільних рядків: контракт власника, правила команд, самодіагностика,
# маршрутизатор запитів, child-контракт. Правила проєкту забороняють runtime
# include · кожен prompt мусить бути самодостатнім, тому спільний текст
# фізично лежить у чотирьох файлах. Наслідок: КОЖНЕ посилення правила треба
# внести чотири рази, і три з чотирьох режимів мовчки лишаються зі старим
# правилом, якщо редагування пропустило файл. Помітити це на прогоні
# неможливо · режим просто поводиться інакше, ніж сусідній.
#
# 2026-08-27 власник зафіксував курс на ЛОКАЛЬНІ моделі. Слабка модель тримає
# рівно те, що написано в її промпті, тому розбіжність між режимами перестає
# бути косметичною: посилене правило, яке доїхало в один файл із чотирьох,
# дає три режими зі старою поведінкою.
#
# Цей тест не забороняє відмінності · він вимагає, щоб вони були ЛИШЕ там, де
# режим справді інший: рядок ідентичності та секції після маршрутизатора.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
fail() { printf 'FAIL: %s\n' "$1" >&2; exit 1; }

PRIMARIES=(патч ручний пропозиції покращення-ші)
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# Спільний блок · від рядка після ідентичності до першої режимної секції.
# Межа задана маркером, а не номером рядка: номери зсуваються з кожною правкою.
shared_block() {
    awk '
        /^Ти диригент /        { started = 1; next }
        started && /^ЩО САМЕ РОБИТЬ ЦЕЙ РЕЖИМ:$/ { exit }
        started && /^ПЕРЕКЛАД:$/                  { exit }
        started                { print }
    ' "$1"
}

for primary in "${PRIMARIES[@]}"; do
    file="$ROOT/.opencode/agents/$primary.md"
    test -f "$file" || fail "немає промпта $primary"
    shared_block "$file" > "$TMP/$primary.txt"
    test -s "$TMP/$primary.txt" || fail "у $primary не знайдено спільного блоку (зник маркер «Ти диригент» або «ПЕРЕКЛАД:»)"
    # Рядок ідентичності мусить бути, і саме він відрізняє режими.
    grep -q '^Ти диригент `[a-z]*`\.' "$file" || fail "$primary не називає свій режим першим рядком"
done

for primary in ручний пропозиції покращення-ші; do
    diff -u "$TMP/патч.txt" "$TMP/$primary.txt" > "$TMP/diff.txt" || {
        printf 'FAIL: спільний блок промпта %s розійшовся з патч:\n' "$primary" >&2
        head -40 "$TMP/diff.txt" >&2
        exit 1
    }
done

# Режимні секції мусять називати ВЛАСНИЙ режим: копіювання спільного блоку не
# має тягти за собою чужий `mode start`.
declare -A MODE=([патч]=patch [ручний]=manual [пропозиції]=proposal [покращення-ші]=improve)
for primary in "${PRIMARIES[@]}"; do
    file="$ROOT/.opencode/agents/$primary.md"
    want="${MODE[$primary]}"
    grep -Fq "Ти диригент \`$want\`." "$file" || fail "$primary називає себе не своїм режимом"
    grep -Fq "./bdo mode start $want" "$file" || fail "$primary не запускає власний режим"
    for other in patch manual proposal improve; do
        test "$other" = "$want" && continue
        grep -Fq "./bdo mode start $other " "$file" && fail "$primary запускає чужий режим $other"
    done
done

echo 'primary prompt drift: OK'
