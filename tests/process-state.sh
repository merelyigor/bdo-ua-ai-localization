#!/usr/bin/env bash
# ЧИ ЖИВИЙ ПРОЦЕС · ОДНА ВІДПОВІДЬ НА ВЕСЬ НАБІР.
#
# Питання ставлять двоє: сторінка (чи ще працює виклик моделі) і команда
# сервера (чи піднятий веб-сервер). До 2026-09-20 відповіді були різні: команда
# сервера вже вміла Windows, а сторінка питала систему рядком `kill -0`. На
# рідному Windows такої команди немає взагалі, тому там живий виклик моделі
# виглядав би завершеним, а картка ролі зникала б з екрана посеред роботи
# (аудит A-06).
#
# Перевірка НЕ підміняє глобальних констант і не залежить від чужого PID:
# платформа передається вимірювачу аргументом, а живий процес береться свій.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
fail() { printf 'FAIL: %s\n' "$1" >&2; exit 1; }

probe() {
    php -r '
    require $argv[1];
    use Bdo\Translate\System\ProcessState;

    $own = new ProcessState();
    $windows = new ProcessState("Windows");

    // 1. Свій процес живий, а порожній і відʼємний PID · ні.
    $results = [
        "свій" => $own->alive(getmypid() ?: 0) ? "живий" : "мертвий",
        "нуль" => $own->alive(0) ? "живий" : "мертвий",
        "відʼємний" => $own->alive(-7) ? "живий" : "мертвий",
    ];

    // 2. ПРОЦЕС, ЯКИЙ ТОЧНО ЗАВЕРШИВСЯ · беремо власну дитину й ховаємо її.
    //    Вигаданий великий номер не годиться: його міг зайняти хтось інший.
    $handle = proc_open([PHP_BINARY, "-r", "exit(0);"], [1 => ["file", "/dev/null", "w"]], $pipes);
    $dead = 0;
    if (is_resource($handle)) {
        $dead = (int) (proc_get_status($handle)["pid"] ?? 0);
        proc_close($handle);
        usleep(200000);
    }
    $results["завершений"] = $dead > 0 && $own->alive($dead) ? "живий" : "мертвий";

    // 3. ГІЛКА WINDOWS ПРОХОДИТЬСЯ ТУТ. На цій машині `tasklist.exe` немає,
    //    тому відповідь · «мертвий», і головне: жодного `kill` не запускається.
    $results["windows"] = $windows->alive(getmypid() ?: 0) ? "живий" : "мертвий";

    foreach ($results as $name => $value) { echo $name, "=", $value, "\n"; }
    ' "$ROOT/lib/autoload.php"
}

out="$(probe)"
grep -Fqx 'свій=живий' <<<"$out" || fail "власний процес названо мертвим: $out"
grep -Fqx 'нуль=мертвий' <<<"$out" || fail "PID 0 названо живим: $out"
grep -Fqx 'відʼємний=мертвий' <<<"$out" || fail "відʼємний PID названо живим: $out"
grep -Fqx 'завершений=мертвий' <<<"$out" || fail "завершений процес названо живим: $out"
grep -Fqx 'windows=мертвий' <<<"$out" \
    || fail "гілка Windows на машині без tasklist мусить відповідати «мертвий»: $out"

# 4. У РОБОЧОМУ КОДІ НЕМАЄ ВЛАСНОГО `kill -0`. Саме він і був непереносним;
#    якщо він повернеться окремою копією, вся ця перевірка нічого не варта.
#    Коментар, який ПОЯСНЮЄ прибраний виклик, порушенням не є · дивимось на
#    рядки коду, а не на текст поруч із ними.
offenders="$(grep -rn "kill -0" "$ROOT/lib" "$ROOT/cli" "$ROOT/bdo" 2>/dev/null \
    | grep -v 'ProcessState.php' \
    | grep -vE ':[0-9]+:[[:space:]]*(//|\*|#)' || true)"
test -z "$offenders" || fail "власний «kill -0» повернувся в робочий код: $offenders"

# 5. Обидва читачі питають ОДИН вимірювач, а не кожен свій.
grep -Fq 'ProcessState())->alive' "$ROOT/lib/Web/Snapshot.php" \
    || fail 'сторінка більше не питає спільний вимірювач живого процесу'
grep -Fq 'ProcessState())->alive' "$ROOT/lib/Cli/Command/System/WebCommand.php" \
    || fail 'команда сервера більше не питає спільний вимірювач живого процесу'

echo 'process state: OK · свій живий, завершений мертвий, гілка Windows проходиться без kill, обидва читачі питають один вимірювач.'
